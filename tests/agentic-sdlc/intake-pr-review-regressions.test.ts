import { baseIssues, harness, MILESTONE, NOW } from "./fixtures/factory-intake";

const intake = require("../../.github/scripts/agentic-intake-runtime.cjs");
const runtime = require("../../.github/scripts/agentic-queue-runtime.cjs");
const promoter = require("../../.github/scripts/agentic-backlog-promoter-runtime.cjs");
const core = require("../../.github/scripts/agentic-backlog-promoter.cjs");
const readiness = require("../../.github/scripts/agentic-factory-readiness.cjs");

const fingerprint = "a".repeat(64);
const reservation = runtime.formatMachineReceipt("reservation", {
  stage: "pm", fingerprint, sourceIssue: 300, state: "reserved",
});
const result = runtime.formatMachineReceipt("result", {
  stage: "pm", fingerprint, issue: 300, bodySha256: "b".repeat(64), completed: true, dispatched: true,
});

function comment(body: string, login = "github-actions[bot]", type = "Bot") {
  return { id: 1, body, created_at: NOW, updated_at: NOW, user: { login, type } };
}

function apply(h: ReturnType<typeof harness>) {
  const source = h.requireIssue(300);
  return intake.applyWorkItemProposal({
    github: h.github, core: h.core, context: h.context(), stage: "pm", now: NOW,
    proposal: { issue: 300, body: source.body, expected_body: source.body, expected_updated_at: source.updated_at },
  });
}

describe("PR331 receipt authority regressions", () => {
  it.each([
    ["copied reservation", reservation, "contributor", "User"],
    ["copied result", result, "contributor", "User"],
    ["malformed marker", '<!-- factory-intake:v1 {"stage":"pm"} -->', "contributor", "User"],
    ["different bot", reservation, "untrusted-bot[bot]", "Bot"],
    ["unknown actor", reservation, "unknown", ""],
    ["quoted machine output", `> ${reservation}`, "github-actions[bot]", "Bot"],
    ["model-owned workflow output", `${reservation}\n\n> Generated by PM Triage\n<!-- gh-aw-workflow-call-id: example/krypto/pm-triage -->`, "github-actions[bot]", "Bot"],
  ])("ignores %s without granting authority or denying legitimate intake", async (_name, body, login, type) => {
    const forged = comment(body, login, type);
    const h = harness({ comments: { 300: [forged] } });

    expect(await apply(h)).toMatchObject({ ok: true, applied: true, issue: 300 });
    expect(h.github.rest.actions.createWorkflowDispatch).toHaveBeenCalledTimes(1);
    expect(await apply(h)).toMatchObject({ ok: true, replayed: true, applied: false });
    expect(h.github.rest.actions.createWorkflowDispatch).toHaveBeenCalledTimes(1);
    expect(h.github.rest.issues.create).not.toHaveBeenCalled();
    expect(readiness.inspectIntakeReceipts([forged])).toMatchObject({ entries: [], reasons: [] });
  });

  it.each([
    ["malformed trusted JSON", comment(reservation.replace('{"stage":"pm"', '{"stage":'))],
    ["edited trusted receipt", { ...comment(reservation), updated_at: "2026-09-16T06:00:00.000Z" }],
  ])("still fails closed on %s", async (_name, record) => {
    const h = harness({ comments: { 300: [record] } });
    expect(await apply(h)).toMatchObject({ ok: false, reasons: ["intake-receipt-unverifiable"] });
    expect(h.github.rest.actions.createWorkflowDispatch).not.toHaveBeenCalled();
    expect(h.github.rest.issues.addLabels).not.toHaveBeenCalled();
    expect(readiness.inspectIntakeReceipts([record]).reasons.length).toBeGreaterThan(0);
  });

  it("does not ignore conflicting trusted reservations", async () => {
    const h = harness({ comments: { 300: [
      comment(reservation),
      { ...comment(reservation), id: 2 },
    ] } });
    expect(await apply(h)).toMatchObject({ ok: false, reasons: ["intake-already-reserved-different-proposal"] });
    expect(h.github.rest.actions.createWorkflowDispatch).not.toHaveBeenCalled();
  });
});

describe("PR331 promoter milestone contract regressions", () => {
  const run = (h: ReturnType<typeof harness>, dryRun = false) => promoter.runBacklogPromoter({
    github: h.github, core: h.core, context: h.context(), config: { now: NOW, dryRun },
  });

  it.each([false, true])("never advertises an unmilestoned issue as promotable (dryRun=%s)", async (dryRun) => {
    const issues = baseIssues();
    issues[2].labels = ["agentic-factory", "ready-for-planning", "risk:routine", "priority:P1"];
    issues[2].milestone = null;
    const h = harness({ issues });
    const original = structuredClone(h.requireIssue(300));
    const candidate = await promoter.buildCandidate({
      github: h.github, core: h.core, owner: "example", repo: "krypto", issue: original, activeGoalNumber: 248,
    });
    const authority = await intake.loadIntakeAuthority({ github: h.github, core: h.core, context: h.context(), now: NOW });
    expect(core.evaluatePromotion(candidate, authority.config)).toMatchObject({
      promotable: false, reasons: expect.arrayContaining(["milestone-binding-requires-intake"]), plan: null,
    });
    const outcome = await run(h, dryRun);
    expect(outcome.plan.promotions).toEqual([]);
    expect(outcome.plan.rejections).toContainEqual(expect.objectContaining({
      number: 300, reasons: expect.arrayContaining(["milestone-binding-requires-intake"]), bucket: "authoring-incomplete",
    }));
    expect(h.requireIssue(300)).toEqual(original);
    expect(h.github.rest.issues.update).not.toHaveBeenCalled();
    expect(h.github.rest.issues.addLabels).not.toHaveBeenCalled();
    expect(h.core.summary.addRaw).toHaveBeenCalledWith(expect.stringContaining("milestone-binding-requires-intake"));
  });

  it("promotes a correctly bound leaf once and does not rewrite its milestone", async () => {
    const issues = baseIssues();
    issues[2].labels = ["agentic-factory", "ready-for-planning", "risk:routine", "priority:P1"];
    const h = harness({ issues });
    expect((await run(h)).promoted).toEqual([300]);
    expect(h.requireIssue(300).labels).toContain("ready-for-ai-dev");
    expect(h.requireIssue(300).milestone).toEqual(MILESTONE);
    expect((await run(h)).promoted).toEqual([]);
    expect(h.github.rest.issues.addLabels).toHaveBeenCalledTimes(1);
    expect(h.github.rest.issues.update).not.toHaveBeenCalled();
  });

  it("binds a new leaf at immutable intake creation without overwriting the unmilestoned source", async () => {
    const issues = baseIssues();
    issues[2].milestone = null;
    const h = harness({ issues });
    const original = structuredClone(h.requireIssue(300));
    const planned = await apply(h);
    expect(planned).toMatchObject({ ok: true, applied: true });
    expect(planned.issue).not.toBe(300);
    expect(h.requireIssue(planned.issue).milestone).toEqual(MILESTONE);
    expect(h.parents.get(planned.issue)).toBe(248);
    expect(h.requireIssue(300)).toEqual(original);
    expect((await run(h)).promoted).toEqual([planned.issue]);
    expect(h.github.rest.issues.create).toHaveBeenCalledTimes(1);
    expect(h.github.rest.issues.update).not.toHaveBeenCalled();
  });
});
